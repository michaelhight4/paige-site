"""Writes interiors_new/INTERIORS.md from the generated maps + pairings.json (run after `maps`)."""
import json, os, glob
from ix_mapkit import D
EXT = {'brookhollow': {(5, 7): 'house_1f', (6, 19): 'heal_centre_int', (16, 19): 'shop_int', (28, 8): 'office_int', (15, 7): 'house_int_a', (28, 19): 'house_int_b'},
       'fernwick': {(5, 6): 'heal_centre_int', (16, 6): 'shop_int', (22, 6): 'house_int_c', (16, 18): 'house_int_a', (5, 17): 'house_int_b', (23, 18): 'fernwick_hall_int'}}
MECH = {'hall_saltmere': 'cracked salt crust (one-step tiles) + 3 latch plates -> seal crystal -> twin gates',
        'hall_revival_heights': 'power cubes onto rail gaps + relay crystal; laser gates with an order trap',
        'hall_lanternport': '5 rotatable mirrors: one lamp beam must light the dock plate and end on the lock receiver; crate blocks beams',
        'hall_cindervale': 'lava trunk with 3 spill branches; cool-stone dams fill basins; bellows reset',
        'hall_aurelith': 'partial gauntlet: beam wing + boulder wing latch two seals; hold plates open the grand gates'}
def main():
    maps = {os.path.basename(f)[:-5]: json.load(open(f)) for f in sorted(glob.glob(os.path.join(D, 'maps', '*.json')))}
    P = json.load(open(os.path.join(D, 'pairings.json')))
    rep = json.load(open(os.path.join(D, 'check_report.json'))) if os.path.exists(os.path.join(D, 'check_report.json')) else {}
    L = []; a = L.append
    a('# Kilumen interiors (new set)\n')
    a('Generated by `python3 tools/interiors_new.py all` (run from `art/world/overworld/`). Everything lives in `interiors_new/`; '
      'nothing in `maps/`, `tileset.json`, `run.py` or the existing `tools/*.py` was touched.\n')
    a('Rules: 64 px native tiles, true pixel art, palette.hex snap with 4x4 Bayer dithering, binary alpha + the one shared shadow rgba(26,18,38,96), '
      'nearest-neighbour 1x/2x/3x. Floors tile seamlessly with 2-3 variants (`seam_report.json` is empty = no seams). Furniture sits on transparent decoration tiles.\n')
    a('## Files\n')
    a('| path | what |\n|---|---|')
    for p, w in [('tools/interiors_new.py', 'entry point: `tiles`, `maps`, `previews`, `check`, `all`; imports tools/pixel.py read-only'),
                 ('interiors_new/gen/', 'generators (tileset, furniture, brand kit, map kit, hall kit, puzzle solver, checks, renderer, this doc)'),
                 ('interiors_new/tileset_interiors.json (+_2x, _3x)', 'interior tileset, ids 7001-7490, every name starts with `i_`'),
                 ('interiors_new/tiles_1x|2x|3x/', 'tile PNGs per scale'),
                 ('interiors_new/maps/*.json', '%d interior maps (same schema as maps/*.json, tileset `../tileset_interiors.json`)' % len(maps)),
                 ('interiors_new/pairings.json', 'machine-readable door pairings (table below)'),
                 ('interiors_new/check_report.json', 'walkability / puzzle report'),
                 ('interiors_new/previews/<map>_1x.png, _3x.png', 'composited previews (3x = nearest-neighbour)'),
                 ('interiors_new/previews/debug/<map>_debug.png', 'collision / warp / NPC / arrival overlay'),
                 ('interiors_new/previews/hall_*_solved_1x.png', 'master halls in their solved state (beams lit, gates open, lava routed)'),
                 ('interiors_new/previews/heal_restyle/', 'Revival Tech restyle: before/, after/, compare_heal_<town>.png')]:
        a('| `%s` | %s |' % (p, w))
    a('\n## Map list\n')
    a('| map | size | kind | title | check |\n|---|---|---|---|---|')
    for k, m in maps.items():
        r = rep.get(k, {}); st = 'FAIL' if r.get('errors') else ('ok, puzzle verified' if r.get('puzzle_verified') else 'ok')
        if r.get('warnings'): st += ' (note: %s)' % '; '.join(r['warnings'])
        a('| %s | %dx%d | %s | %s | %s |' % (k, m['width'], m['height'], m.get('kind', ''), m.get('title', ''), st))
    a('\nThe "unreachable" notes on marts and heal branches are the staff cells behind the counters (on purpose).\n')
    a('## Door pairings\n')
    a('Interiors for settlements whose exteriors are not built yet exit through a warp with `"to": "$return"` and a `pair_with` '
      '`{map, door}` naming the planned exterior door. When an exterior is built, its door warp should target the interior below and land on the arrival cell. '
      'Two-tile mats share one pairing.\n')
    a('| interior | exit mat(s) | arrival (x,y) | exterior map | door key | exterior door xy | status |\n|---|---|---|---|---|---|---|')
    seen = {}
    for p in P:
        key = (p['interior'], p['map'], p['door'])
        if key in seen: seen[key]['warp'] += [p['warp']]; continue
        q = dict(p); q['warp'] = [p['warp']]; seen[key] = q
    for k, m in maps.items():
        if k.startswith('hall_'):
            ws = [w for w in m['warps'] if w.get('pair_with')]
            pw = ws[0]['pair_with']
            seen[(k, pw['map'], pw['door'])] = dict(interior=k, warp=[[w['x'], w['y']] for w in ws], arrival=pw.get('interior_arrival'),
                                                    map=pw['map'], door=pw['door'], door_xy=None, status='planned')
    for q in seen.values():
        a('| %s | %s | %s | %s | %s | %s | %s |' % (q['interior'], ' '.join('(%d,%d)' % tuple(w) for w in q['warp']), tuple(q['arrival']) if q['arrival'] else '-',
                                                    q['map'], q['door'], tuple(q['door_xy']) if q['door_xy'] else '-', q['status']))
    a('\nStairs between a home and its `_2f` map are internal warps (not `$return`), listed in each map\'s `warps`.\n')
    a('## Existing exteriors: re-pointing plan (NOT applied, maps/ is owned by another worker)\n')
    a('Current door warps in `maps/brookhollow.json` and `maps/fernwick.json` all point at shared interiors. Proposed change, '
      'per door (keep the door tile; edit only `to`, `tx`, `ty`). The new interiors already exit back to the exact door tile, one row below it.\n')
    a('| exterior | door xy | now -> | re-point to | new tx,ty |\n|---|---|---|---|---|')
    newmap = {}
    for p in P:
        if p.get('door_xy') and p['map'] in EXT: newmap.setdefault((p['map'], tuple(p['door_xy'])), (p['interior'], p['arrival']))
    for t, ds in EXT.items():
        for xy, now in ds.items():
            if (t, xy) in newmap:
                i, arr = newmap[(t, xy)]; a('| %s | %s | %s | **%s** | %d,%d |' % (t, xy, now, i, arr[0], arr[1]))
            else:
                why = {'house_1f': 'keep (player home, story map)', 'office_int': 'keep (RT field office; story map)', 'shop_int': 'keep (shared mart already fits; no new mart needed)',
                       'fernwick_hall_int': 'keep (existing master hall)'}.get(now, 'keep')
                a('| %s | %s | %s | %s | - |' % (t, xy, now, why))
    a('\nAfter re-pointing, `house_int_a/b/c` and `heal_centre_int` are no longer used by Brookhollow/Fernwick; leave them in maps/ until no other map refers to them. '
      '`station_int` (shared, 20x13) should be replaced by the four per-city stations: each Lumen Line stop door targets `station_<city>` (arrival (7,8)), '
      'and rail arrivals use the map\'s `platform_arrival` field ((7,3) facing down). No current exterior points at `station_int`, so nothing has to be re-pointed today. '
      'New doors are needed on `brookhollow.json` for `lab_brookhollow` (there is no lab door; the existing (28,8) door is the RT field office and stays as is).\n')
    a('''## Revival Tech branches (heal centres)

All seven heal centres (`heal_<town>`) are Revival Tech branches: violet trim, an original crystal-mark logo panel (a faceted crystal over three rising chevrons, not based on any existing brand), uniformed carer behind an `i_counter_rt_*` counter, a crystal-polishing station in place of the healing machine, company posters, a suggestion box, a newsletter rack and a locked STAFF ONLY door at (10,2).
Brookhollow and Fernwick keep the exact footprint (14x10), exit mats (6,9)+(7,9) and arrival of `heal_centre_int`; the other towns use a 13x9 branch. Before/after images: `previews/heal_restyle/`.

Back room: `rt_branch_backroom` (one shared map, exits via `$return`). In every branch the staff door is listed in `locked_warps`:
`{x:10, y:2, approach:[10,3], to:"rt_branch_backroom", tx:4, ty:4, locked:true, unlock_flag:"rt_backroom_open", collision_when_unlocked:4}`.
While the flag is unset the cell is collision 1 with a sign ("STAFF ONLY"). To unlock: when `rt_backroom_open` is set, write 4 into the collision cell and add the entry to `warps`.

The HQ lobby (`rt_hq_lobby`) uses the same kit; its four lifts are blocking `i_lift` objects listed in `locked_lifts` (unlock flag `rt_hq_lifts_open`, target floors not built).
''')
    a('## Master halls and puzzles\n')
    a('Fernwick\'s hall already exists (`maps/fernwick_hall_int.json`) and was skipped. Each new hall carries `puzzle` with rules text, element lists, the start, the goal, and '
      '`puzzle.verified` from `gen/ix_puzzles.py` (BFS over player position, boulders/stones, switch bits, collapsed crust and mirror states, plus a reverse BFS: '
      '`softlock_states` = states from which the goal can no longer be reached without a reset/exit).\n')
    a('| hall | mechanic | states explored | soft-locks | shortest solution |\n|---|---|---|---|---|')
    for k, m in maps.items():
        if 'puzzle' in m:
            v = m['puzzle']['verified']
            a('| %s | %s | %s | %s | `%s` |' % (k, MECH.get(k, ''), v['states_explored'], v['softlock_states'], v['shortest_solution']))
    a('''
Solution legend: U/D/L/R steps, a `*` marks a step that pushes, `n` repeats, `A<id>` = interact (rotate mirror, touch crystal, pump bellows).

Engine notes the game code must match (see `gen/ix_puzzles.py`):
* **no_push**: `puzzle.no_push` is a list of cells that boulders/stones/crates can never be pushed onto (door sills, gate cells, bellows fronts). It exists to stop crates being shoved through a gate into an unreachable pocket.
* **Lava spill model** (Cindervale): `lava.trunk` is the ordered channel from the source; it is hot up to the first cool stone sitting in it. `lava.spill` lists [junction, first branch cell]; a branch only fills when the trunk is dammed just below its junction, and branch flow never re-enters the trunk. A basin plate is on while lava reaches it. The player can never end a move on hot lava; cool stones can be pushed onto hot cells (that is how you dam). There is no step timing: flow is instant.
* **Seals and zones** (Aurelith): a seal latches for good once its source channel is on; wing zones reset on exit unless their seal is latched.
* Hold plates / beam plates count only while occupied / lit; latch plates stay on until a reset crystal.

`tools/run.py`'s solver only models boulders + switches, so it cannot check these halls; use `gen/ix_puzzles.py` (`python3 tools/interiors_new.py check`).
''')
    a('''## Stations (Lumen Line)

`station_saltmere`, `station_lanternport`, `station_revival_heights` (Central) and `station_aurelith`: 16x10, timetables, route posters, ticket counter with a `station_attendant` (talk from (13,7)), turnstiles, benches, luggage, rail buffer.
`platform_arrival` (7,3) facing down is where FIELD_SKILLS.md rail travel drops the player. Revival Heights Central adds the `rail_pass_clerk` (gives `has_rail_pass`); Revival Heights and Aurelith add an airspace officer.

## Lab

`lab_brookhollow` (14x11): lead researcher, aide, three starter cradles at (5,5),(7,5),(9,5) (read from y=7, flag `got_starter` in `story`), lab machines, specimen tanks, server racks. Needs a new `lab` door on Brookhollow.

## Gaps / open items

* Exteriors for Saltmere, Cindervale, Lanternport, Revival Heights and Aurelith do not exist yet, so all their pairings are `$return` + `pair_with` (planned).
* Brookhollow needs a new lab door; Revival Heights needs an `rt_hq` door; station cities need `station` doors.
* Re-pointing of the five Brookhollow/Fernwick doors listed above has not been applied (maps/ is owned by another worker).
* `heal_centre_int.json`, `shop_int.json` and `station_int.json` in maps/ are not edited (the shared shop stays as Brookhollow/Fernwick's mart).
* No Brookhollow master hall (the town has no master in the design docs).
* Halls for Frostspire, Mirefen and Tidewater are out of scope for this pass.
* Aurelith's gauntlet is partial: 2 of the 8 planned wings (beam and boulder) plus the twin-seal gate; the fog, tide, ice, lava, crust and crystal-set wings and the champion remix room are not built.
* Lanternport's day/night beam switch and boat lanes are simplified to a fixed mirror puzzle.
* Lava timing is simplified (spill model, no timed flow).
* `tools/run.py` solver lacks the new verbs (mirrors, crust, lava, seals, no_push), so it cannot verify these halls.
* NPCs are placed as markers with `text_ref` keys; dialogue lines are left for the Text Bot, and the NPC sprites are markers only.
* HQ upper floors (lift targets) are not built.
''')
    open(os.path.join(D, 'INTERIORS.md'), 'w').write('\n'.join(L))
    print('INTERIORS.md written')
if __name__ == '__main__':
    import sys; sys.path.insert(0, os.path.dirname(__file__)); main()
