// Regenerates src/battle/data/ron_pools.gen.js: the lineage pools Ron's rolled slots draw from (Coder, Oct 29 2026).
// A pool = base forms (line roots) of every species in that region's wild tables (data/encounters_wired.json) that are
// registered (src/ui/data.js SPECIES) and have battle art (species_with_art AND an art/characters/pixel/creatures/<id> folder), minus starter lines and Ron's base 3 lines.
// Run: node tools/ron/gen_ron_pools.mjs
import fs from 'node:fs';
import { SPECIES } from '../../src/ui/data.js';
import { evoTable } from '../../src/systems/evolution.js';
import { STARTER_LINES } from '../../src/battle/data/starters.js';

const enc = JSON.parse(fs.readFileSync('data/encounters_wired.json', 'utf8'));
const art = new Set(enc.species_with_art.filter((s) => fs.existsSync(`art/characters/pixel/creatures/${s}`) && !/^tbd/.test(s))), reg = new Set(SPECIES.map((s) => s.id)), t = evoTable();
const prevo = {}; for (const [id, e] of Object.entries(t)) prevo[e.to] = id;
const root = (s) => { while (prevo[s]) s = prevo[s]; return s; };
const line = (s) => { const out = [s]; while (t[s]) { s = t[s].to; out.push(s); } return out; };
const banned = new Set([...Object.values(STARTER_LINES).flat(), ...line('peeplark'), 'sailquill']);
// Zones per Ron fight region (the region the fight happens in).
export const FIGHT_ZONES = {
  ron_1: ['sunmeadow_grass'],
  ron_2: ['route_east_grass', 'route_aurelith_saltmere_grass', 'saltmere_water', 'thornwood_grass'],
  ron_3: ['route_revival_grass', 'route_revival_tr_crystal_grass', 'route_revival_saltmere_grass', 'greystone_glowfern'],
  ron_4: ['frostspire_pass_grass', 'frostspire_grass', 'frostspire_cave'],
  ron_5: ['route_coast_grass', 'tidewater_coast_grass', 'tidewater_coast_cave', 'tidewater_coast_water'],
  ron_6: ['lanternport_water', 'lanternport_grotto_cave'],
  ron_final: ['route_cindervale_grass', 'route_cindervale_cave', 'cindervale_caldera_cave', 'route_fernwick_lanternport_grass'],
};
const pools = {};
for (const [f, zones] of Object.entries(FIGHT_ZONES)) {
  const set = new Set();
  for (const z of zones) for (const sl of enc.zones[z]?.slots || []) {
    if (sl.stand_in || sl.placeholder) continue;
    const r = root(sl.species);
    if (reg.has(r) && art.has(r) && !banned.has(r)) set.add(r);
  }
  pools[f] = [...set].sort();
}
// Every form Ron may field (base lines + all pool lines + starter lines) that is registered and has art: stageFor stops
// before a form outside this list.
const ok = new Set();
for (const r of [...Object.values(pools).flat(), 'peeplark', 'sailquill', ...Object.keys(STARTER_LINES)]) for (const s of line(r)) if (reg.has(s) && art.has(s)) ok.add(s);
const src = `// GENERATED by tools/ron/gen_ron_pools.mjs from data/encounters_wired.json. Do not edit by hand.
// Ron's rolled-slot lineage pools per fight (line roots; registered + battle art; no starter lines, no Ron base-3 lines).
export const RON_POOLS = ${JSON.stringify(pools, null, 1)};
export const RON_FORMS_OK = ${JSON.stringify([...ok].sort())};
`;
fs.writeFileSync('src/battle/data/ron_pools.gen.js', src);
for (const [f, p] of Object.entries(pools)) console.log(f, p.length, p.join(' '));
