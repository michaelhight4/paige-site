#!/usr/bin/env node
// Builds data/trail_axes.json: the progression axis of every trail map (internal ids route*, incl. variants) for wild
// level scaling (src/battle/level_scale.js; Gary 11:48 AM CT Oct 23 2026: "well we need to have them be level scaling the
// closer to town you get").
// Derivation (map data only): hop distance from the home town (HOME, Brookhollow) over the map graph (edge exits + warps).
// Entry = the trail exit whose target is closest to home (the earlier, home-side town); equal hop distance -> lower hall
// coin number (data/masters.json halls[].coin_number; no hall = 0) is earlier. Far end = the exit whose target is
// furthest (same order); ties prefer a non-trail target (a town), then the edge opposite the entry, then file order. a/b = the
// exits' cells; span = min/max projection of every encounter-zone cell onto a->b (so the first grass patch is t=0 and the
// last is t=1). Overrides: data/trail_axes_overrides.json {"maps": {"<map>": {"entry": "<to>", "exit": "<to>"} |
// {"a": [x,y], "b": [x,y]} | {"skip": true}}}.  Usage: node tools/build_trail_axes.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { exitPoint, project } from '../src/battle/level_scale.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MAPS = join(ROOT, 'art/world/overworld/maps');
const OUT = join(ROOT, 'data/trail_axes.json');
const OVR = join(ROOT, 'data/trail_axes_overrides.json');
export const HOME = 'brookhollow';
const isTrail = (name) => /^route/.test(name);
const OPP = { north: 'south', south: 'north', east: 'west', west: 'east' };

export function loadMaps() {
  const maps = {};
  for (const f of readdirSync(MAPS).filter((f) => f.endsWith('.json'))) { const m = JSON.parse(readFileSync(join(MAPS, f), 'utf8')); maps[m.name || f.slice(0, -5)] = m; }
  const vdir = join(MAPS, 'variants'), variants = {};
  if (existsSync(vdir)) for (const f of readdirSync(vdir).filter((f) => f.endsWith('.json'))) { const m = JSON.parse(readFileSync(join(vdir, f), 'utf8')); variants[m.name || f.slice(0, -5)] = m; }
  return { maps, variants };
}

export function hopDistances(maps, home = HOME) {
  const dist = { [home]: 0 }, q = [home];
  while (q.length) {
    const n = q.shift(), m = maps[n]; if (!m) continue;
    for (const to of [...(m.exits || []).map((e) => e.to), ...(m.warps || []).map((w) => w.to)]) {
      if (to && maps[to] && dist[to] == null) { dist[to] = dist[n] + 1; q.push(to); }
    }
  }
  return dist;
}

export function deriveAxis(map, dist, ovr = {}, coin = {}) {
  const ord = (to) => dist[to] * 100 + (coin[to] || 0);
  if (ovr.skip) return null;
  const exits = (map.exits || []).filter((e) => e.to && dist[e.to] != null);
  let entry, far;
  if (ovr.a && ovr.b) { entry = { a: ovr.a }; far = { b: ovr.b }; }
  else {
    if (exits.length < 2 && !(ovr.entry && ovr.exit)) return null;
    entry = ovr.entry ? exits.find((e) => e.to === ovr.entry) : [...exits].sort((p, q) => ord(p.to) - ord(q.to))[0];
    if (!entry) return null;
    const rest = exits.filter((e) => e !== entry);
    far = ovr.exit ? rest.find((e) => e.to === ovr.exit) : [...rest].sort((p, q) => (ord(q.to) - ord(p.to))
      || (isTrail(p.to) - isTrail(q.to)) || ((q.edge === OPP[entry.edge]) - (p.edge === OPP[entry.edge])))[0];
    if (!far || ord(far.to) <= ord(entry.to) && !ovr.exit) return null; // no forward direction
  }
  const a = ovr.a || exitPoint(map, entry), b = ovr.b || exitPoint(map, far);
  let s0 = Infinity, s1 = -Infinity;
  for (const r of map.encounter_zones || []) for (let y = r.y0; y <= r.y1; y++) for (let x = r.x0; x <= r.x1; x++) {
    const p = project(a, b, x, y); s0 = Math.min(s0, p); s1 = Math.max(s1, p);
  }
  if (!(s1 > s0)) { s0 = 0; s1 = 1; }
  const r3 = (v) => Math.round(v * 1000) / 1000;
  return { from: entry.to ?? null, to: far.to ?? null, entry_edge: entry.edge ?? null, exit_edge: far.edge ?? null, a, b, span: [r3(s0), r3(s1)], source: ovr.a || ovr.entry ? 'override' : 'derived' };
}

export function buildAxes() {
  const { maps, variants } = loadMaps(), dist = hopDistances(maps);
  const halls = existsSync(join(ROOT, 'data/masters.json')) ? JSON.parse(readFileSync(join(ROOT, 'data/masters.json'), 'utf8')).halls || [] : [];
  const coin = Object.fromEntries(halls.map((h) => [h.zone, h.coin_number || 0]));
  const ovr = existsSync(OVR) ? JSON.parse(readFileSync(OVR, 'utf8')).maps || {} : {};
  const out = { _about: 'Trail progression axes for wild level scaling (src/battle/level_scale.js). Generated by tools/build_trail_axes.mjs from map exits/warps; edit data/trail_axes_overrides.json, not this file.', home: HOME, maps: {} };
  const all = { ...maps, ...variants };
  for (const name of Object.keys(all).sort()) {
    if (!isTrail(name)) continue;
    const ax = deriveAxis(all[name], dist, ovr[name] || ovr[all[name].variant_of] || {}, coin);
    if (ax) out.maps[name] = ax;
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const txt = JSON.stringify(buildAxes(), null, 1) + '\n';
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    console.log(cur === txt ? 'up to date' : 'STALE: run node tools/build_trail_axes.mjs'); process.exit(cur === txt ? 0 : 1);
  }
  writeFileSync(OUT, txt);
  for (const [n, a] of Object.entries(JSON.parse(txt).maps)) console.log(n.padEnd(30), `${a.from} (${a.entry_edge}) -> ${a.to} (${a.exit_edge})  span ${a.span}`);
}
