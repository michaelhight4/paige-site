#!/usr/bin/env node
// Builds Kilumen's OPTIONAL installable-PWA service worker with workbox-build (MIT; LICENSE read in
// tools/free_tools/node_modules/workbox-build/LICENSE, Oct 22, 2026). Dev tool only; workbox's runtime is inlined
// into the generated worker, so nothing from node_modules is served.
//
// The live game is unchanged unless the page is opened with ?pwa=1 (or PWA_ENABLED in pwa/pwa_register.js is set
// to true). See pwa/README.md.
//
// Usage (from /workspace/kilumen):
//   (cd tools/free_tools && npm ci)   # once
//   node tools/pwa_build.mjs          # -> kilumen-sw.js (repo root, so its scope covers the whole game) + pwa/sw_build.js
//   BUILD_ID=test2 node tools/pwa_build.mjs   # force a build id (tests use this to simulate a new version)
//
// Versioning: BUILD_ID = sha1(package version + every precached file's revision + path/size/mtime of every file under
// art/ and audio/), first 10 hex chars. Every cache name contains it (kilumen-<id>-precache..., kilumen-<id>-art,
// kilumen-<id>-audio), and pwa/sw_build.js deletes every other "kilumen-" cache when the new worker activates, so an
// update can never leave players on stale art/audio.
import { createRequire } from 'node:module';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(path.join(ROOT, 'tools/free_tools/package.json'));
let wb;
try { wb = req('workbox-build'); } catch (e) { console.error('workbox-build missing. Run: (cd tools/free_tools && npm ci)'); process.exit(2); }

const SW_FILE = 'kilumen-sw.js';
const BUILD_FILE = 'pwa/sw_build.js';
// Game shell = everything needed to boot and play without the network, except art/audio (runtime-cached on first use).
const shellGlobs = [
  'index.html', 'style.css', 'manifest.webmanifest',
  'src/**/*.{js,mjs,css,json}',
  'text/**/*.json',
  'pwa/kilumen.webmanifest', 'pwa/pwa_register.js', 'pwa/icons/*.png',
];
const globIgnores = ['**/node_modules/**', 'src/**/*.patch', 'src/**/*.md', 'src/vendor/**/LICENSE*', 'pwa/sw_build.js'];
const common = { globDirectory: ROOT, globPatterns: shellGlobs, globIgnores, maximumFileSizeToCacheInBytes: 4 * 1024 * 1024 };

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else { const s = fs.statSync(p); out.push(`${path.relative(ROOT, p)}|${s.size}|${Math.floor(s.mtimeMs)}`); }
  }
  return out;
}

const pre = await wb.getManifest(common);
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const h = crypto.createHash('sha1');
h.update(pkg.version || '0');
for (const e of pre.manifestEntries) h.update(`${e.url}|${e.revision}\n`);
for (const d of ['art', 'audio']) if (fs.existsSync(path.join(ROOT, d))) for (const l of walk(path.join(ROOT, d)).sort()) h.update(l + '\n');
const BUILD_ID = (process.env.BUILD_ID || h.digest('hex').slice(0, 10)).replace(/[^a-zA-Z0-9_-]/g, '');
const PREFIX = `kilumen-${BUILD_ID}`;

fs.writeFileSync(path.join(ROOT, BUILD_FILE), `// GENERATED by tools/pwa_build.mjs. Do not edit. Imported by ${SW_FILE}.
// Build id and cache cleanup: on activate, delete every "kilumen-" cache that doesn't belong to this build.
self.KILUMEN_SW_BUILD = ${JSON.stringify(BUILD_ID)};
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys
    .filter((k) => k.startsWith('kilumen-') && !k.startsWith(${JSON.stringify(PREFIX + '-')}))
    .map((k) => caches.delete(k)))));
});
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'KILUMEN_SW_BUILD') event.ports[0] && event.ports[0].postMessage({ build: self.KILUMEN_SW_BUILD });
});
`);

const res = await wb.generateSW({
  ...common,
  swDest: path.join(ROOT, SW_FILE),
  mode: 'production',
  inlineWorkboxRuntime: true,
  sourcemap: false,
  cacheId: PREFIX,
  importScripts: [`${BUILD_FILE}?v=${BUILD_ID}`],
  skipWaiting: true,     // a new build takes over on the next load; old caches are deleted on activate
  clientsClaim: true,
  cleanupOutdatedCaches: true,
  navigateFallback: 'index.html',
  navigateFallbackAllowlist: [/\/(index\.html)?(\?.*)?$/],
  ignoreURLParametersMatching: [/.*/], // index.html?pwa=1&save=0... all map to the precached index.html
  runtimeCaching: [
    { urlPattern: ({ url, sameOrigin }) => sameOrigin && /\/art\//.test(url.pathname), handler: 'CacheFirst',
      options: { cacheName: `${PREFIX}-art`, expiration: { maxEntries: 3000, purgeOnQuotaError: true }, cacheableResponse: { statuses: [200] } } },
    { urlPattern: ({ url, sameOrigin }) => sameOrigin && /\/audio\//.test(url.pathname), handler: 'CacheFirst',
      options: { cacheName: `${PREFIX}-audio`, expiration: { maxEntries: 200, purgeOnQuotaError: true }, cacheableResponse: { statuses: [200] }, rangeRequests: true } },
  ],
});
const swBytes = fs.statSync(path.join(ROOT, SW_FILE)).size, bBytes = fs.statSync(path.join(ROOT, BUILD_FILE)).size;
const out = { buildId: BUILD_ID, precacheEntries: res.count, precacheBytes: res.size, swBytes, swBuildBytes: bBytes, warnings: res.warnings };
fs.writeFileSync(path.join(ROOT, 'pwa/last_build.json'), JSON.stringify(out, null, 2) + '\n');
console.log(JSON.stringify(out));
