// Builds src/sports/data/athletics.gen.js: athletic stat ranges + trait odds for every species (Kilumen sports, dev).
// node tools/sports/gen_athletics.mjs [--check]   (--check: exit 1 if the file on disk is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SPECIES } from '../../src/ui/data.js';
import { STATS, TRAITS, TYPE_CENTRE, HALF_WIDTH, shapeOf, SHAPES, BASE_LEAN, LEAN_CAP, STAGE_SHIFT, TRAIT_LEAN, SHAPE_TRAIT } from '../../src/sports/rules.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'src/sports/data/athletics.gen.js');
const OVR = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/sports/data/athletics_overrides.json'), 'utf8'));
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const bs = (s, k) => (Array.isArray(k) ? k.reduce((n, x) => n + (s.baseStats?.[x] ?? 60), 0) / k.length : s.baseStats?.[k] ?? 60);

export function buildTable() {
  const out = {};
  for (const s of SPECIES) {
    const ov = OVR[s.id] || {};
    const els = (s.el || ['normal']).filter((e) => TYPE_CENTRE[e]);
    const types = els.length ? els : ['normal'];
    const shapeName = ov.shape || shapeOf(s.id)[0];
    const shapeDelta = (SHAPES.find(([n]) => n === shapeName) || [0, 0, {}])[2];
    const stage = STAGE_SHIFT[s.stage] ?? STAGE_SHIFT[1];
    const ranges = {}, centre = {};
    for (const st of STATS) {
      // primary type counts double when dual-typed
      let c = types.length === 1 ? TYPE_CENTRE[types[0]][st] : (2 * TYPE_CENTRE[types[0]][st] + TYPE_CENTRE[types[1]][st]) / 3;
      const [k, per] = BASE_LEAN[st];
      c += clamp(((bs(s, k) - 60) / 10) * per, -LEAN_CAP, LEAN_CAP);
      c += shapeDelta[st] || 0;
      c += stage;
      c += ov.shift?.[st] || 0;
      c = Math.round(c);
      centre[st] = c;
      ranges[st] = ov.range?.[st] || [clamp(c - HALF_WIDTH, 3, 85), clamp(c + HALF_WIDTH, 17, 99)];
    }
    const tw = {};
    for (const t of TRAITS) tw[t] = Math.max(1, Math.round(5 + (centre[TRAIT_LEAN[t]] - 50) / 5 + (SHAPE_TRAIT[shapeName]?.[t] || 0) + (ov.traits?.[t] || 0)));
    out[s.id] = { shape: shapeName, ranges, traitWeights: tw };
  }
  return out;
}

const text = (t) => `// GENERATED by tools/sports/gen_athletics.mjs from src/sports/rules.js + data/athletics_overrides.json. Do not hand-edit.\n// ${Object.keys(t).length} species. Each: body shape guess, [lo,hi] per athletic stat (1-100), trait weights.\nexport const ATHLETICS = ${JSON.stringify(t)};\n`;
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const t = text(buildTable());
  if (process.argv.includes('--check')) { const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === t; console.log(ok ? 'athletics.gen.js up to date' : 'athletics.gen.js OUT OF DATE'); process.exit(ok ? 0 : 1); }
  fs.writeFileSync(OUT, t); console.log('wrote', OUT);
}
export { text as tableText };
