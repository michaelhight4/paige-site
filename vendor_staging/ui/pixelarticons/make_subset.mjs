// Run from the repo root: node vendor_staging/ui/pixelarticons/make_subset.mjs
// Excluded on purpose (content rules): bottle-wine, cigarette, cigarette-off and anything alcohol / drug / smoking related.
import { readFileSync, writeFileSync } from 'node:fs';
const SRC = 'vendor_staging/ui/pixelarticons/package/svg/';
const NAMES = ['users', 'backpack', 'book-open', 'clipboard-note', 'map', 'contact', 'save', 'sliders', 'archive', 'store', 'sword', 'menu',
  'heart', 'zap', 'cloud', 'tree', 'sun', 'speed-medium', 'volume-3', 'volume-x', 'music', 'audio-waveform', 'gamepad', 'shopping-cart',
  'leaf', 'tools', 'diamond-gem', 'key', 'notebook', 'trending-up', 'sparkles', 'info-box'];
const BANNED = /wine|beer|cocktail|cigar|smok|drug|pill|syringe|bottle/;
const out = {};
for (const n of NAMES) {
  if (BANNED.test(n)) throw new Error('banned icon ' + n);
  const svg = readFileSync(SRC + n + '.svg', 'utf8');
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error('unexpected viewBox ' + n);
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
}
const hdr = `// pixelarticons 2.4.2 subset (${NAMES.length} of 1036 icons), MIT License, Copyright (c) 2019 Gerrit Halfmann. See ./LICENSE.\n// Source: https://registry.npmjs.org/pixelarticons/-/pixelarticons-2.4.2.tgz (github.com/halfmage/pixelarticons).\n// Generated by vendor_staging/ui/pixelarticons/make_subset.mjs. 24x24 grid, fill="currentColor". Do not edit by hand.\n`;
writeFileSync('src/vendor/pixelarticons/icons.js', hdr + 'export const PXI = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log('wrote', NAMES.length, 'icons');
